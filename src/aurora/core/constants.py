EQ_DESIGN_ITERATIONS: Final = 12
EQ_DESIGN_MAX_CORRECTION_DB: Final = 12.0

# ---------------------------------------------------------------- 空間音效

#: STFT 視窗長度。1024 @48k 約 47 Hz 解析度 —— 足以分辨「人聲」與「殘響」
#: 的相關性差異，這裡不做外科手術式的音源分離，不需要更細。
#:
#: **延遲等於這個值**（1024 框 ≈ 21 ms），不是 ``fft_size − hop``。
#: 前者是 STFT 的演算法延遲，但輸出只能以 hop 為單位產生，而回呼大小是
#: 裝置決定的任意值 —— 為了任何 block 大小都不 underrun，輸出佇列必須
#: 預填滿一個完整視窗。已用模擬驗證 ``fft_size − hop`` 的預填在
#: block=64／2880 時會 underrun。
#:
#: **視窗大小由效能決定，不是由頻率解析度決定。**
#:
#: 一度用 1024（延遲 21 ms），但加入 depth 與早期反射之後整條鏈超出章程
#: §6.3 的預算（device 實測 mean 15.65%，上限 10%）。Profile 顯示瓶頸
#: **不是 FFT**（只佔 0.96 ms），而是每個 hop 上數十次 numpy 呼叫的累積
#: 開銷 —— 2880 框的回呼在 hop=512 下要跑 5.6 個 hop。
#:
#: 所以唯一有效的槓桿是**減少 hop 數**：
#:
#: ==========  ==========  =========  ========
#: fft/hop     每回呼 hop  成本        延遲
#: ==========  ==========  =========  ========
#: 1024/512    5.6         4.435 ms   21.3 ms
#: 2048/1024   2.8         2.514 ms   42.7 ms
#: 4096/2048   1.4         2.618 ms   85.3 ms
#: ==========  ==========  =========  ========
#:
#: 2048 便宜 43%；再往上 FFT 成本的成長抵銷了 hop 減少，只剩延遲變差。
SPATIAL_FFT_SIZE: Final = 2048
#: 跳距。50% 重疊，sqrt-Hann 在這個重疊下相加為 1，可完美重建。
#:
#: 視窗與跳距兩個長度、以及下面兩個「每 hop」平滑係數，都是在
#: DSP_REFERENCE_RATE 下定的；其他取樣率下依 ``core/rates.py`` 縮放。
SPATIAL_HOP: Final = 1024
#: 相關性的時間平滑係數（一階遞迴，越大越平滑）。**每個參考 hop 的值**：
#: 實際的 hop 長度不同時換算成同一個時間常數（約 131 ms）。
#:
#: 一定要平滑。逐框的瞬時相關性抖動很大，直接拿來當增益會讓穩定的人聲
#: 每 20 ms 被推一次，聽起來像有東西在呼吸。0.85 在「跟得上轉場」與
#: 「不抖」之間。
SPATIAL_COHERENCE_SMOOTHING: Final = 0.85
#: 環繞（環境音）成分的音量，定義成「全開時環境音 side 的能量倍率」
#: ``1 + level²``（振幅倍率 ``hypot(1, level)``）。
#:
#: 這個定義沿用自舊的隨機相位做法 —— 當時環繞副本與原始 side 以功率相加，
#: 側能量正好是 ``1 + level²``。現在立體聲路徑直接把環境音 side 乘上同樣的
#: 能量倍率（見 ``spatial.py`` 的 ``_render_stereo``），所以這個值、以及
#: 拿兩支 Dolby Atmos 測試片定下它的那組實測（500–2 kHz 加寬 1.73x）
#: 的意義都不變，差別只在沒有了梳狀染色與預回音。
#: 1.8 可再推到 2.0x，但那個程度容易聽出相位味，且已無滑桿餘裕可退。
SPATIAL_SURROUND_LEVEL: Final = 1.4
#: 原始 side 成分的寬度倍率。1.0 = 不改變原本的立體聲寬度。
SPATIAL_WIDTH: Final = 1.0
#: 雙耳 renderer 餵給環繞喇叭的去相關濾波器：每一格的群延遲落在
#: ``[DELAY, DELAY + SPREAD]`` 毫秒之間。
#:
#: **不能用「每格獨立的隨機相位」。** 那種濾波器的脈衝響應是鋪滿整個 STFT
#: 視窗的白噪音，而頻域相乘是環形卷積，一半的能量會繞到**負時間**——
#: 實測一個 2 ms 的擴散瞬態，前 25 ms 就開始出聲，瞬態前的能量從
#: −30.8 dB 被抬到 −11.1 dB，也就是明顯的預回音。
#:
#: 把群延遲限制在一個區間裡，脈衝響應就被關在那段時間內：1～11 ms 讓 94%
#: 的能量落在前 12 ms、繞回負時間的只剩 3.6%。下限 1 ms 讓第一個抽頭
#: 不與原訊號同時到達；區間長度 10 ms 讓 300 Hz（護欄的上緣，週期 3.3 ms）
#: 以上仍然去相關得開。再長則繞回的比例開始上升（20 ms 時 12.8%）。
#: 雙耳 renderer 裡「這一格有多置中」的權重，沿頻率平滑的寬度（八度）。
#:
#: 權重會變成補償的相位乘數（``w·φ``）。每一格各自算的話，相鄰兩格的 ``w``
#: 差很多，相位在頻率方向上亂跳，脈衝響應鋪滿整個視窗、繞回負時間 —— 與
#: 隨機相位去相關器同一類問題，實測擴散瞬態前 2–40 ms 的能量被抬到 −15 dB
#: （輸入是 −30.8 dB）。用直達功率加權、平滑 1/3 八度後是 −32.9 dB，而置中
#: 內容的音色與偏位的 ILD 完全不變；再寬（1/2、1 八度）只再好 0.7 dB。
#: 1/3 八度也是本專案其他頻譜平滑的慣用寬度（``HRTF_EQ_SMOOTHING_OCTAVE``）。
SPATIAL_CENTRE_SMOOTHING_OCTAVE: Final = 1.0 / 3.0
SPATIAL_DECORRELATION_DELAY_MS: Final = 1.0
SPATIAL_DECORRELATION_SPREAD_MS: Final = 10.0
#: 環境音加寬（以及雙耳的環繞饋給）只作用在這個頻率以上（Hz），以下平滑地
#: 淡出到完全不處理。
#:
#: 低頻隨機相位會讓低音聲像散掉 —— 內部研究文件把它叫做
#: 「low-frequency phase chaos」，並建議在去相關網路後做適度 high-pass。
#: 實測未加時 <200 Hz 的 side 能量被推高 1.09 倍；低音本來就該緊實置中。
#: 淡出從 SPATIAL_DECORRELATION_HP_HZ 的一半開始，避免硬邊造成鈴振。
#:
#: 220 Hz 在環繞量還是 1.0 時夠用，但拉到 1.4 之後淡入區漏出來的量變大，
#: 低頻又被推高到 1.09x（測試抓到的回歸）。300 Hz 讓 <200 Hz 回到 0.995x，
#: 而 500–2 kHz 的加寬完全沒有損失。再往上拉沒有效果 —— 剩餘的量測差異
#: 是 STFT 暖機假影，不是去相關造成的。
#:
#: 立體聲路徑改成直接放大環境音 side 之後，理由從「隨機相位散掉低音」變成
#: 「低頻 side 被放大就是低音聲像變寬」—— 同一個護欄、同一個頻率。
SPATIAL_DECORRELATION_HP_HZ: Final = 300.0

#: 全開時把「直達成分」壓低多少 dB —— 這是**距離**的機制。
#:
#: 人耳判斷距離主要靠 direct/reverberant 比，門檻在數 dB。加這條之前，
#: 乾濕比從 0 拉到 100% 只讓 D/R 變 −0.62 dB（實測），遠低於可察覺範圍，
#: 所以無論怎麼調參數都不可能「拉遠」—— 那是機制缺席，不是數值不夠。
#:
#: 只壓直達（主成分）的部分，擴散成分不動，D/R 才會真的改變。直達成分的
#: mid 與 side **一起壓**：以前只壓 mid，偏位樂器的 side 沒動，等於把它往外
#: 推（實測偏左 6 dB 的乾聲源被推到 10.9 dB）。見 ``spatial.py`` 的
#: :meth:`SpatialUpmix._analyse`。壓完之後有全域響度補償，否則使用者會把
#: 「變小聲」誤認成「變遠」。
#: −5 dB 在實測上給出約 −5 dB 的 D/R 變化，足以察覺又不會把人聲挖空。
SPATIAL_DEPTH_DB: Final = -6.0
#: 深度曲線的指數。depth 依 amount**這個指數**推進，而不是直接依 amount。
#:
#: D/R 的分子與分母同時在變（直達被壓低、side 同時增加），所以直接用
#: amount 會得到一條凸曲線 —— 實測 50% 只走完 27% 的深度。指數 0.45 把
#: 線性度誤差從 23% 壓到 15%，讓滑桿刻度大致對應可量化的距離變化。
#: 無法做到完全線性，那是兩個機制交互作用的結果，不是可調參數的問題。
SPATIAL_DEPTH_CURVE: Final = 0.45
#: 響度補償的時間平滑。補償對 mid 與 side 等量施加，所以總響度回來、
#: D/R 比保留。平滑是為了避免逐框變動造成抽吸感。與相關性平滑一樣是
#: 每個參考 hop 的值（見 DSP_REFERENCE_RATE）。
SPATIAL_MAKEUP_SMOOTHING: Final = 0.85
#: 補償增益的上限（線性）。內容幾乎全是置中時補償會偏大，夾住避免失控。
SPATIAL_MAKEUP_CEILING: Final = 2.0

# ---------------------------------------------------------------- 早期反射

#: 兩個離散反射的到達時間（毫秒）。
#:
#: 人耳判斷空間大小靠的是最早幾個反射的到達時間 —— 牆越遠，第一次反射
#: 越晚。11 與 23 ms 對應一個中型房間。
#:
#: **只有兩個抽頭，而且沒有回授。** 一旦加入回授就會長出殘響尾巴，
#: 「空間感」立刻變成「浴室」。這一級刻意保持簡陋。
REFLECTION_TAP_MS: Final[tuple[float, ...]] = (11.0, 23.0)
#: 反射相對直達聲的音量。保守 —— 過量就從空間感變成回音。
REFLECTION_LEVEL: Final = 0.22
#: 每一個後續反射的衰減倍率。
REFLECTION_DECAY: Final = 0.7
#: 反射送到**對側**聲道的比例。左的反射主要落在右邊，模擬側牆路徑。
#:
#: 它只影響**偏在一側**的內容。置中內容左右相同，交叉之後兩聲道的反射仍然
#: 一樣，每個聲道都是原聲加延遲副本的梳狀濾波（全開 −4.1～+2.8 dB）——
#: 以前這裡說交叉餵送能避免梳狀濾波，對置中內容不成立。為什麼在立體聲
#: 路徑上消不掉，見 ``reflections.py`` 的模組 docstring。
REFLECTION_CROSSFEED: Final = 0.7
#: 反射的帶通範圍（Hz）。
#:
#: 高通：低頻反射只會讓聲音變糊，而且低頻的方向性線索本來就弱 ——
#: 與 spatial.py 的低頻護欄同一個理由。
#: 低通：真實牆面反射會損失高頻（空氣與材質吸收），這本身就是距離線索；
#: 不做的話反射聽起來像數位回音。
REFLECTION_HP_HZ: Final = 300.0
REFLECTION_LP_HZ: Final = 7000.0
#: 帶通 FIR 的抽頭數。奇數。用 FIR 而不是一階遞迴，理由與 eq.py 相同：
#: IIR 在時間上遞迴，numpy 無法向量化。
#:
#: 長度受**低頻解析度**支配，跟 eq.py 是同一個物理限制：48 kHz 下 33 抽頭
#: 只有約 1455 Hz 的解析度，根本做不出 300 Hz 的高通（實測 100 Hz 只被
#: 抑制到 0.79）。實測 129 抽頭 0.295、257 抽頭 0.061。
#: 取 257：抑制夠乾淨，兩聲道卷積約 0.66 ms。
REFLECTION_KERNEL_TAPS: Final = 257

#: 雙耳反射的虛擬牆面方位角（度，偏離正前方；左右各一面）。
#:
#: 刻意與環繞喇叭同一個角度，理由是**資料**而不是聲學上的最佳解：實測
#: profile 的 ``.npz`` 只存 0°／30°／110° 三個方位角，用第四個角度會讓現有
#: 的 profile 在載入時整組失效、靜靜退回合成模型。側牆的一次反射落在 110°
#: 也站得住腳，而「60° 是不是更好」由 ``tools/make_reflection_test.py`` 的
#: 離線盲測回答 —— 那條路直接讀資料集，不必先改 npz 格式。
REFLECTION_AZIMUTH_DEG: Final = 110.0
#: 雙耳反射卷積核的長度（抽頭）。
#:
#: 核心是「HRTF × 帶通」的合成，所以長度由兩者相加決定。實測四組資料
#: （合成模型／H13／KEMAR／KU100）的 99.99% 能量都落在 285 抽頭以內，
#: 取 385 留了一倍餘裕；截掉的尾巴能量在 1e-5 量級。
#:
#: **不要縮短它到帶通群延遲以下。** 合成模型的近耳響應是負延遲（波前比
#: 正前方早到），irfft 之後那一段會繞到緩衝區尾端；是帶通的 128 樣本群延遲
#: 把它推回因果區的（110° 的半個 ITD 只有 16 樣本）。這個「剛好」有測試守著。
REFLECTION_HRTF_TAPS: Final = 385
#: 取樣 HRTF 用的 FFT 長度。只在 prepare 時用一次，不在回呼上。
#:
#: 要夠長讓 ``HRTF_MAX_TAP_RATIO`` 的上限（視窗的 1/4）容得下常見資料集的
#: HRIR：2048 → 512 抽頭，而實測的三組是 173～178 抽頭。
REFLECTION_HRTF_FFT_SIZE: Final = 2048
#: 一面虛擬牆的餵法裡，**近側**聲道佔的比例。
#:
#: 兩個值得記的點：
#:
#: **一、方向與立體聲那條路相反，而且是刻意的。** 交叉餵送模擬的是
#: 「左聲道打到右牆再回到左耳」那條**橫越**房間的路徑——沒有 HRTF 時，
#: 那是唯一能讓兩耳有差別的辦法。有 HRTF 之後對側耳的路徑由遠耳響應
#: ``h_c`` 正確算出來，就不需要那個代用品了，於是改回物理上更直接的模型：
#: 左邊的內容主要打到**左**牆。早期側向反射之所以能撐開音場，靠的正是
#: 反射方向與聲源方向相關。
#:
