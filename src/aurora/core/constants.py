#: 再短的話 31 Hz 那一段就沒有東西可以塑形（31 Hz 一個週期要 1548 個樣本），
#: 再長則延遲開始影響歌詞對齊與未來的 A/V 同步。
#:
#: 這是 DSP_REFERENCE_RATE 下的值；其他取樣率依 ``core/rates.py`` 換算成同樣的
