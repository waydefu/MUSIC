# ---------------------------------------------------------------- 等化器

#: 10 段 ISO 標準中心頻率（Hz）。
EQ_BAND_HZ: Final[tuple[float, ...]] = (
    31.0, 62.0, 125.0, 250.0, 500.0, 1000.0, 2000.0, 4000.0, 8000.0, 16000.0
)
#: 每段的增益上下限（dB）。章程 §7.1 訂 ±12。
EQ_GAIN_LIMIT_DB: Final = 12.0
