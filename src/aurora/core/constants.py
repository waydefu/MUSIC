#: 頻段中心修正到位，31 Hz 也會被帶高 9.5 dB。β=3 的主瓣窄一截，同一個
#: 情況只帶高約 6.8 dB；代價是 500 Hz 以上多了 ±0.2 dB 以內的漣波，
#: 遠低於可察覺的門檻。
EQ_WINDOW_BETA: Final = 3.0
